// Builds src/components/icons.generated.ts: one inline SVG sprite (Lucide, ISC licence)
// plus two hand-drawn brand marks. Run: node scripts/build-icons.mjs
import { readFileSync, writeFileSync } from 'node:fs';

const map = {
  cap: 'graduation-cap', bulb: 'lightbulb', rocket: 'rocket', megaphone: 'megaphone', printer: 'printer',
  gift: 'gift', handshake: 'handshake', scales: 'scale', globe: 'globe', chart: 'chart-line', pin: 'map-pin',
  sparkle: 'sparkles', play: 'play', palette: 'palette', box: 'package', receipt: 'receipt', shield: 'shield-check',
  phone: 'phone', share: 'share-2', prev: 'chevron-left', next: 'chevron-right', down: 'chevron-down',
  sun: 'sun', moon: 'moon', menu: 'menu', close: 'x', star: 'star', arrow: 'arrow-right', chat: 'message-circle',
};
const custom = {
  instagram: '<rect x="3" y="3" width="18" height="18" rx="5"/><circle cx="12" cy="12" r="4"/><circle cx="17.5" cy="6.5" r="0.6" fill="currentColor"/>',
  whatsapp: '<path d="M3.5 20.5l1.3-4.2A8.5 8.5 0 1 1 8 19.6z"/><path d="M9 8.6c.2-.5.6-.6.9-.6h.4l1 2.2-.6.8c.5 1 1.3 1.8 2.3 2.3l.8-.6 2.2 1v.4c0 .3-.1.7-.6.9-.9.5-2.3.3-4-1.1a8 8 0 0 1-2-2.3C8.7 10.3 8.6 9.3 9 8.6z"/>',
};
let symbols = '';
for (const [id, file] of Object.entries(map)) {
  const svg = readFileSync(`node_modules/lucide-static/icons/${file}.svg`, 'utf8');
  const inner = svg.slice(svg.indexOf('>', svg.indexOf('<svg')) + 1, svg.lastIndexOf('</svg>')).replace(/\s+/g, ' ').trim();
  symbols += `<symbol id="i-${id}" viewBox="0 0 24 24">${inner}</symbol>`;
}
for (const [id, inner] of Object.entries(custom)) symbols += `<symbol id="i-${id}" viewBox="0 0 24 24">${inner}</symbol>`;

const out = `// GENERATED by scripts/build-icons.mjs — do not edit. Icons: Lucide (ISC licence).
export const ICON_SPRITE = ${JSON.stringify(
  `<svg xmlns="http://www.w3.org/2000/svg" class="sprite" aria-hidden="true" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">${symbols}</svg>`,
)};
export const ICON_NAMES = ${JSON.stringify([...Object.keys(map), ...Object.keys(custom)])} as const;
export type IconName = (typeof ICON_NAMES)[number];
`;
writeFileSync('src/components/icons.generated.ts', out);
console.log('sprite bytes:', symbols.length);
